    /**
     * Creates a 256x256 font atlas texture containing 256 ASCII character glyphs (16x16 grid of 16x16 px cells).
     * Procedurally generated in pure memory with zero Android graphics/ashmem allocations.
     * Returns the OpenGL ES 2.0 Texture Handle.
     */
    fun createFontAtlasTexture(): Int {
        val atlasSize = 256
        val cellSize = 16

        val rawGrid = ByteArray(atlasSize * atlasSize * 4)

        for (i in 0 until 256) {
            val charToDraw = if (i < asciiChars.size) asciiChars[i] else (i % 95 + 32).toChar()
            val col = i % 16
            val row = i / 16
            val cellStartX = col * cellSize
            val cellStartY = row * cellSize

            val pattern = getGlyph8x8Pattern(charToDraw)

            // Render 8x8 pattern scaled 2x to fill 16x16 cell centered
            for (py in 0 until 8) {
                val rowBits = pattern[py].toInt()
                for (px in 0 until 8) {
                    val isSet = (rowBits and (0x80 ushr px)) != 0
                    val alpha: Byte = if (isSet) (-1).toByte() else 0

                    // 2x2 block per bit
                    for (dy in 0..1) {
                        for (dx in 0..1) {
                            val targetX = cellStartX + px * 2 + dx
                            val targetY = cellStartY + py * 2 + dy
                            if (targetX < atlasSize && targetY < atlasSize) {
                                val offset = (targetY * atlasSize + targetX) * 4
                                rawGrid[offset] = (-1).toByte()     // R
                                rawGrid[offset + 1] = (-1).toByte() // G
                                rawGrid[offset + 2] = (-1).toByte() // B
                                rawGrid[offset + 3] = alpha         // A
                            }
                        }
                    }
                }
            }
        }

        val byteBuffer = ByteBuffer.allocateDirect(rawGrid.size).order(ByteOrder.nativeOrder())
        byteBuffer.put(rawGrid)
        byteBuffer.position(0)

        val textures = IntArray(1)
        GLES20.glGenTextures(1, textures, 0)
        val textureId = textures[0]

        GLES20.glBindTexture(GLES20.GL_TEXTURE_2D, textureId)
        GLES20.glTexParameteri(GLES20.GL_TEXTURE_2D, GLES20.GL_TEXTURE_MIN_FILTER, GLES20.GL_NEAREST)
        GLES20.glTexParameteri(GLES20.GL_TEXTURE_2D, GLES20.GL_TEXTURE_MAG_FILTER, GLES20.GL_NEAREST)
        GLES20.glTexParameteri(GLES20.GL_TEXTURE_2D, GLES20.GL_TEXTURE_WRAP_S, GLES20.GL_CLAMP_TO_EDGE)
        GLES20.glTexParameteri(GLES20.GL_TEXTURE_2D, GLES20.GL_TEXTURE_WRAP_T, GLES20.GL_CLAMP_TO_EDGE)

        GLES20.glTexImage2D(
            GLES20.GL_TEXTURE_2D,
            0,
            GLES20.GL_RGBA,
            atlasSize,
            atlasSize,
            0,
            GLES20.GL_RGBA,
            GLES20.GL_UNSIGNED_BYTE,
            byteBuffer
        )

        return textureId
    }
