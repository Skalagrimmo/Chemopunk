        '>', '(', ')', '[', ']', '{', '}', '^', '_', '~', '`', '\'', '"', ';', ','
    )

    val charIndexMap = IntArray(256) { idx ->
        val ch = idx.toChar()
        val listIdx = asciiChars.indexOf(ch)
        if (listIdx >= 0) listIdx else (idx % 95 + 32)
    }

    val glyphUvs = Array(256) { idx ->
        val glyphIdx = if (idx in 0..255) charIndexMap[idx] else 0
        val col = glyphIdx % 16
        val row = glyphIdx / 16
        floatArrayOf(
            col / 16.0f,
            row / 16.0f,
            (col + 1.0f) / 16.0f,
            (row + 1.0f) / 16.0f
        )
    }

    /**
     * Returns UV coordinates [uMin, vMin, uMax, vMax] for an ASCII character.
     */
    fun getGlyphUv(char: Char): FloatArray {
        val code = char.code and 0xFF
        return glyphUvs[code]
    }

    /**
     * Returns the 0..255 index of the glyph in the 16x16 font atlas.
     */
    fun getGlyphIndex(char: Char): Int {
        val code = char.code and 0xFF
        return charIndexMap[code]
    }

